#!/usr/bin/env python3
"""Writes the Android theme palettes from the Apple app's (App/DesignSystem/Theme/ThemePalettes*.swift),
which stay the single source of truth for color. Run after changing a palette there."""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCES = sorted((ROOT / "App/DesignSystem/Theme").glob("ThemePalettes*.swift"))
OUTPUT = ROOT / "Android/app/src/main/java/com/adamhunt/retroguide/ui/theme/ThemePalettes.kt"
ORDER = ["classicCable", "localForecast", "saturdayMorning", "payPerView", "woodPanel", "vhs",
         "synthwave", "midnight", "crtGreen", "amber", "teletext", "mono"]
FIELDS = ["surface", "surfaceRaised", "focusFill", "textPrimary", "textSecondary", "textOnFocus",
          "accent", "accentSecondary", "nowLine", "osd"]
AUDIENCES = ["kids", "family", "teen", "mature", "unrated"]


def color(hex_value):
    return f"Color(0xFF{hex_value.lstrip('#').upper()})"


def audience_map(text):
    pairs = dict(re.findall(r"\.(\w+):\s*Color\(hex:\s*\"(#[0-9A-Fa-f]{6})\"\)", text))
    return "mapOf(" + ", ".join(f"Audience.{a.upper()} to {color(pairs[a])}" for a in AUDIENCES) + ")"


source = "\n".join(path.read_text() for path in SOURCES)
standard = audience_map(re.search(r"standardAudienceColors[^=]*=\s*\[(.*?)\]", source, re.S).group(1))
themes = {}
for match in re.finditer(r"static let (\w+) = Theme\((.*?)\n    \)", source, re.S):
    name, body = match.groups()
    values = {field: re.search(rf"\b{field}:\s*Color\(hex:\s*\"(#[0-9A-Fa-f]{{6}})\"\)", body).group(1) for field in FIELDS}
    background = re.findall(r"#[0-9A-Fa-f]{6}", re.search(r"backgroundColors:\s*\[(.*?)\]", body, re.S).group(1))
    title = re.search(r'name:\s*"([^"]+)"', body).group(1)
    audience = re.search(r"audienceColors:\s*(\[.*?\]|standardAudienceColors)", body, re.S).group(1)
    audiences = "STANDARD_AUDIENCE_COLORS" if audience == "standardAudienceColors" else audience_map(audience)
    themes[name] = (title, background, values, audiences)

lines = [
    "package com.adamhunt.retroguide.ui.theme",
    "",
    "import androidx.compose.ui.graphics.Color",
    "",
    "// Generated by Android/Scripts/generate-themes.py from the Apple app's palettes. Don't edit by hand.",
    "",
    f"private val STANDARD_AUDIENCE_COLORS = {standard}",
    "",
    "/** The built-in themes in picker order. */",
    "val ThemePalettes: List<Theme> = listOf(",
]
for key in ORDER:
    title, background, values, audiences = themes[key]
    lines.append("    Theme(")
    lines.append(f"        id = ThemeId.{re.sub(r'(?<!^)(?=[A-Z])', '_', key).upper()},")
    lines.append(f'        name = "{title}",')
    lines.append(f"        background = listOf({', '.join(color(c) for c in background)}),")
    for field in FIELDS:
        lines.append(f"        {field} = {color(values[field])},")
    lines.append(f"        audienceColors = {audiences},")
    lines.append("    ),")
lines.append(")")
OUTPUT.write_text("\n".join(lines) + "\n")
print(f"wrote {len(ORDER)} themes to {OUTPUT.relative_to(ROOT)}")
